"""Embed the saturation package's Metal source and compiled SPIR-V."""
from pathlib import Path
import json

root = Path(__file__).resolve().parent
data = (root / "saturation.frag.spv").read_bytes()
output = ["/* Generated by shaders/embed.py. */"]
output.append("static const char saturation_metal[] = " + json.dumps((root / "saturation.metal").read_text()) + ";")
output.append("static const unsigned char saturation_spv[] = {\n" + ",".join(str(x) for x in data) + "\n};")
(root.parent / "shaders.h").write_text("\n".join(output) + "\n")
