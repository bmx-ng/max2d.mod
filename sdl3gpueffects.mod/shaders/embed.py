"""Embed the built-in image-effect Metal sources and compiled SPIR-V."""
from pathlib import Path
import json

root = Path(__file__).resolve().parent
output = ["/* Generated by shaders/embed.py. */"]
for name in ("saturation", "blur"):
    data = (root / (name + ".frag.spv")).read_bytes()
    output.append("static const char " + name + "_metal[] = " + json.dumps((root / (name + ".metal")).read_text()) + ";")
    output.append("static const unsigned char " + name + "_spv[] = {\n" + ",".join(str(x) for x in data) + "\n};")
(root.parent / "shaders.h").write_text("\n".join(output) + "\n")
