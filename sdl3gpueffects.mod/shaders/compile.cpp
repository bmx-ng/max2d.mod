// Build tool only; applications use the checked-in shader package.
#include <windows.h>
#include <d3dcompiler.h>
#include <fstream>
#include <iterator>
#include <string>
#include <cstdio>

int main(int argc,char **argv) {
	if(argc!=3 && argc!=4) return 1;
	std::ifstream input(argv[1]);
	if(!input) return 1;
	std::string source((std::istreambuf_iterator<char>(input)),std::istreambuf_iterator<char>());
	std::string name=argc==4?argv[3]:"saturation";
	if(name!="saturation" && name!="blur" && name!="colorize" && name!="outline") return 1;
	std::string entry=name+"Main";
	ID3DBlob *code=nullptr,*errors=nullptr;
	HRESULT result=D3DCompile(source.data(),source.size(),argv[1],nullptr,nullptr,entry.c_str(),"ps_5_1",D3DCOMPILE_OPTIMIZATION_LEVEL3,0,&code,&errors);
	if(errors) {
		fwrite(errors->GetBufferPointer(),1,errors->GetBufferSize(),stderr);
		errors->Release();
	}
	if(FAILED(result)) return 1;
	FILE *output=fopen(argv[2],"wb");
	if(!output) { code->Release(); return 1; }
	fprintf(output,"/* Generated by shaders/compile.cpp from %s.hlsl. */\nstatic const unsigned char %s_dxbc[]={\n",name.c_str(),name.c_str());
	auto bytes=(const unsigned char *)code->GetBufferPointer();
	for(size_t i=0;i<code->GetBufferSize();++i)
		fprintf(output,"0x%02x,%s",bytes[i],(i%16==15 || i+1==code->GetBufferSize())?"\n":" ");
	fprintf(output,"};\n");
	code->Release();
	return fclose(output)!=0;
}
